const dictionaries: Record<Lang, Record<Key, string>> = { en, tr };

export function initialLang(): Lang {
  try {
    const saved = localStorage.getItem("aitrack.lang");
    if (saved === "en" || saved === "tr") return saved;
  } catch {
    // Storage unavailable; fall through.
  }
  return navigator.language.toLowerCase().startsWith("tr") ? "tr" : "en";
}

export function translator(lang: Lang) {
  const dict = dictionaries[lang];
  return (key: Key, vars: Record<string, string | number> = {}) =>
    dict[key].replace(/\{(\w+)\}/g, (m, name: string) => (name in vars ? String(vars[name]) : m));
}

export type T = ReturnType<typeof translator>;

export const I18nContext = createContext<{ t: T; lang: Lang }>({ t: translator("en"), lang: "en" });
export const useI18n = () => useContext(I18nContext);
